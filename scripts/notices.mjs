import { execFileSync } from "node:child_process";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { webpVersion } from "./native-webp.mjs";
import { prepareNativeCodecs } from "./native-codecs.mjs";
import { avifVersion, aomVersion } from "./native-avif.mjs";

const packages = [
  "github.com/gen2brain/webp", "github.com/gen2brain/avif",
  "github.com/gen2brain/jpegxl", "github.com/gen2brain/heic",
  "github.com/tetratelabs/wazero", "github.com/andybalholm/brotli",
  "golang.org/x/image",
];
const modules = execFileSync("go", ["list", "-m", "-f", "{{.Path}}\t{{.Version}}\t{{.Dir}}", ...packages], { encoding: "utf8" });
const native = await prepareNativeCodecs();
const sections = ["Pic Piper bundled image codecs\nGenerated by scripts/notices.mjs from the pinned codec sources.\n\nThe app uses bundled codecs; no runtime system codec libraries are loaded.\n"];
if (native) {
  sections.push(`\n${"=".repeat(72)}\nlibwebp ${webpVersion} (statically linked still-image encoder)\nhttps://chromium.googlesource.com/webm/libwebp/\n`);
  for (const file of ["COPYING", "PATENTS"]) {
    sections.push(`\n--- ${file} ---\n${readFileSync(join(native.sources.webp, file), "utf8")}\n`);
  }
  for (const [id, version, files] of [
    ["avif", avifVersion, ["LICENSE"]],
    ["aom", aomVersion, ["LICENSE", "PATENTS", "third_party/libyuv/LICENSE", "third_party/fastfeat/LICENSE", "third_party/vector/LICENSE", "third_party/x86inc/LICENSE", "third_party/highway/LICENSE-BSD3"]],
  ]) {
    sections.push(`\n${"=".repeat(72)}\nlib${id} ${version} (statically linked AVIF encoder)\n`);
    for (const file of files) {
      sections.push(`\n--- ${file} ---\n${readFileSync(join(native.sources[id], file), "utf8")}\n`);
    }
  }
}
sections.push(`\n${"=".repeat(72)}\nLittleCMS 2.20 (portable ICC engine)\nhttps://github.com/mm2/Little-CMS\n${readFileSync("internal/imaging/icc/LICENSE", "utf8")}\n`);
for (const row of modules.trim().split("\n")) {
  const [name, version, directory] = row.split("\t");
  sections.push(`\n${"=".repeat(72)}\n${name} ${version}\nhttps://${name}\n`);
  for (const folder of [directory, join(directory, "lib")]) {
    if (!existsSync(folder)) continue;
    for (const file of readdirSync(folder).sort()) {
      if (/^(LICENSE|COPYING|NOTICE)(\.|$)/i.test(file)) {
        sections.push(`\n--- ${file} ---\n${readFileSync(join(folder, file), "utf8")}\n`);
      }
    }
  }
}
writeFileSync("resources/codec-notices.txt", `${sections.join("\n").trimEnd()}\n`);
console.log("Collected bundled codec license notices.");
